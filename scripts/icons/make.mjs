if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const nodes = JSON.parse(readFileSync(join(PKG, 'icon-nodes.json'), 'utf8'))
  const { version, license } = JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8'))
  const missing = NAMES.filter((n) => !nodes[n])
  if (missing.length) throw new Error('not in lucide-static ' + version + ': ' + missing.join(', '))
  if (new Set(NAMES).size !== NAMES.length) throw new Error('a name is listed twice')
  const body = [...NAMES].sort().map((n) => `  '${n}': ${JSON.stringify(nodes[n])},`).join('\n')
  const out = `// Generated by scripts/icons/make.mjs from lucide-static ${version} (${license}; Copyright (c) Lucide
// Icons and Contributors, part derived from Feather, MIT, Copyright (c) 2013-present Cole Bemis:
// THIRD-PARTY-NOTICES.md). Do not edit: change the list in the script and run it again.
// Each icon is drawn in a 24 x 24 box with stroke="currentColor", no fill.

/** One icon: its SVG elements (tag and attributes), in order. */
export type IconNode = readonly (readonly [string, Readonly<Record<string, string>>])[]

export const ICONS = {
${body}
} as const satisfies Record<string, IconNode>

export type IconName = keyof typeof ICONS

/** The package the shapes were copied from. */
export const ICON_SOURCE = { name: 'lucide-static', version: '${version}', license: '${license}' } as const
`
  mkdirSync(join(APP, 'src', 'renderer', 'src', 'ui', 'icons'), { recursive: true })
  writeFileSync(join(APP, 'src', 'renderer', 'src', 'ui', 'icons', 'lucide.ts'), out)
  console.log(`${NAMES.length} icons from lucide-static ${version}`)
}
